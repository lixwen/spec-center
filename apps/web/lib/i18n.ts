const dictionaries: Record<Locale, MessageTree> = {
  en: englishMessages,
  "zh-CN": chineseMessages
};

function mergeMessages(base: MessageTree, override: MessageTree): MessageTree {
  const result: MessageTree = { ...base };

  for (const [key, value] of Object.entries(override)) {
    const baseValue = result[key];

    if (
      value &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      baseValue &&
      typeof baseValue === "object" &&
      !Array.isArray(baseValue)
    ) {
      result[key] = mergeMessages(baseValue as MessageTree, value as MessageTree);
      continue;
    }

    result[key] = value as string | string[] | MessageTree;
  }

  return result;
}

export function isSupportedLocale(value?: string | null): value is Locale {
  return supportedLocales.includes(value as Locale);
}

export function normalizeLocale(value?: string | null): Locale {
  if (isSupportedLocale(value)) {
    return value;
  }

  if (value?.toLowerCase().startsWith("zh")) {
    return "zh-CN";
  }

  return "en";
}

export function getMessages(locale: Locale) {
  return mergeMessages(englishMessages, dictionaries[locale]) as typeof englishMessages;
}

